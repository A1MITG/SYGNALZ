# scripts/archive_snapshot.py
"""File the last build of each day into the daily archive.

Run by .github/workflows/build-signals.yml at the start of every build,
before the new data is written. public/command_center_data.json then still
holds the previous build. When that build was made on an earlier IST day
than today, it was that day's last build, so it is filed as
    public/snapshots/YYYY-MM-DD.json
and never rewritten. A day's snapshot therefore appears with the first build
of the next day (the 00:00 IST slot), and holds exactly what the site showed
at the end of that day. A day with no build has no snapshot.

Storage is kept to the minimum: minified JSON, with the fields the archive
page does not draw left out (about 46 KB a day, about 17 KB once git or
Vercel compresses it). The /archive page (public/archive.html, generated by
scripts/build_command_center_data.py) lists the days from the files present.
"""
import json
import re
import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_DIR = ROOT / 'public'
# Not public/archive/: on Vercel /archive is the page (archive.html).
ARCHIVE_DIR = PUBLIC_DIR / 'snapshots'
IST = timezone(timedelta(hours=5, minutes=30))
DAY_FILE = re.compile(r'^\d{4}-\d{2}-\d{2}\.json$')


def ist_date(iso):
    """The IST calendar date of an ISO timestamp, as YYYY-MM-DD."""
    return datetime.fromisoformat(iso).astimezone(IST).date().isoformat()


def slim(data):
    """The day's data with what the archive page never draws left out."""
    data = dict(data)
    # _featured is a copy of _features[0], kept for older pages.
    if data.get('_features'):
        data.pop('_featured', None)
    meta = dict(data.get('_meta') or {})
    # No "next refresh" on a past day, and no live-fetch stamp.
    for key in ('refresh_slots_ist', 'fetched_minutes_ago', 'data_date'):
        meta.pop(key, None)
    data['_meta'] = meta
    if isinstance(data.get('_record'), dict):
        data['_record'] = {k: v for k, v in data['_record'].items() if k != 'generated'}
    return data


def archived_dates(archive_dir=ARCHIVE_DIR):
    """Every day on file, oldest first."""
    if not archive_dir.is_dir():
        return []
    return sorted(p.stem for p in archive_dir.iterdir() if DAY_FILE.match(p.name))


def snapshot(now=None, public_dir=PUBLIC_DIR):
    """File the previous build if it was a past day's last. Returns the path or None."""
    source = public_dir / 'command_center_data.json'
    if not source.is_file():
        return None
    data = json.loads(source.read_text(encoding='utf-8'))
    built_at = (data.get('_meta') or {}).get('built_at')
    if not built_at:
        return None
    day = ist_date(built_at)
    today = (now or datetime.now(timezone.utc)).astimezone(IST).date().isoformat()
    if day >= today:
        return None   # still today: a later build may replace it
    out = public_dir / ARCHIVE_DIR.name / f'{day}.json'
    if out.exists():
        return None   # already filed; a day's snapshot is never rewritten
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(slim(data), ensure_ascii=False, separators=(',', ':')),
                   encoding='utf-8')
    return out


